"""Bounded physical source-size feedback. Clippy owns semantic Rust analysis."""

import fnmatch
import os
import re
from pathlib import Path

from .models import CheckConfig
from .models import Issue
from .models import Severity


def excluded(path: Path, patterns: list[str]) -> bool:
    """Match complete components or relative path suffixes, not substrings."""
    parts = path.as_posix().split("/")
    for pattern in patterns:
        directory = pattern.removesuffix("/**")
        if any(fnmatch.fnmatch(part, directory) for part in parts):
            return True
        if any(
            fnmatch.fnmatch("/".join(parts[index:]), pattern) or fnmatch.fnmatch("/".join(parts[index:]), directory)
            for index in range(len(parts))
        ):
            return True
    return False


def source_files(paths: list[str], config: CheckConfig):
    """Only explicit directories are walked; ignored directories are pruned."""
    patterns = config.exclude_patterns + config.structure_exclude_patterns
    seen: set[Path] = set()
    for name in paths:
        path = Path(name)
        if path.is_dir() and not excluded(path, patterns):
            for directory, dirs, files in os.walk(path):
                dirs[:] = [name for name in dirs if not excluded(Path(directory) / name, patterns)]
                for name in files:
                    candidate = Path(directory) / name
                    resolved = candidate.resolve()
                    if candidate.suffix == ".rs" and resolved not in seen:
                        seen.add(resolved)
                        yield candidate
        elif path.suffix == ".rs" or path.is_dir():
            resolved = path.resolve()
            if resolved not in seen:
                seen.add(resolved)
                yield path


def generated_header(content: str) -> bool:
    """Recognize leading generated comments without interpreting Rust syntax."""
    for line in content.split("\n", 10)[:10]:
        line = line.strip()
        if not line:
            continue
        if re.match(r"(?://[!/]?|/\*)\s*(?:@generated\b|automatically generated\b|generated by\b)", line, re.I):
            return True
        if not line.startswith("//"):
            break
    return False


def notice(path: Path, code: str, message: str) -> Issue:
    return Issue(
        file=str(path),
        line=1,
        column=1,
        code=code,
        message=message,
        severity=Severity.INFO if code == "STRUCTURE-EXCLUDED" else Severity.WARNING,
        source="structure",
    )


def read_source(path: Path, config: CheckConfig) -> tuple[str | None, list[Issue]]:
    """Read at most limit+1 bytes once; a skip never claims complete analysis."""
    patterns = config.exclude_patterns + config.structure_exclude_patterns
    if excluded(path, patterns) or excluded(path.resolve(), patterns):
        return None, [notice(path, "STRUCTURE-EXCLUDED", "Source analysis excluded by path configuration.")]
    try:
        with path.open("rb") as stream:
            raw = stream.read(config.structure_max_bytes + 1)
        if len(raw) > config.structure_max_bytes:
            return None, [notice(path, "STRUCTURE-SKIPPED", "Size/stub analysis skipped: source exceeds byte limit.")]
        content = raw.decode("utf-8-sig")
    except (OSError, UnicodeError) as error:
        return None, [notice(path, "STRUCTURE-SKIPPED", f"Size/stub analysis unavailable: {type(error).__name__}.")]
    if config.structure_exclude_generated and generated_header(content):
        return None, [notice(path, "STRUCTURE-EXCLUDED", "Source analysis excluded: generated-source header.")]
    lines = content.count("\n") + int(bool(content) and not content.endswith("\n"))
    issues = []
    if lines > config.max_file_lines:
        issues.append(
            notice(
                path,
                "FILE-LENGTH",
                f"File has {lines} physical lines (warning threshold {config.max_file_lines}); review its responsibilities.",
            )
        )
    return content, issues
