@pytest.mark.parametrize("enabled", [False, True])
def test_clippy_advisories_share_existing_invocation_without_expanding_scope(tmp_path, enabled):
    checker = RustChecker(CheckConfig(enable_clippy_advisories=enabled), tmp_path)
    with patch(
        "amplifier_bundle_rust_dev.checker.subprocess.run", return_value=subprocess.CompletedProcess([], 0, "", "")
    ) as run:
        result = checker._run_clippy(tmp_path)
    command = run.call_args.args[0]
    assert run.call_count == 1 and result.clean
    assert command[:6] == ["cargo", "clippy", "--message-format=json", "--", "-W", "clippy::all"]
    assert ("clippy::cognitive_complexity" in command) is enabled
    assert ("clippy::too_many_lines" in command) is enabled
    assert "--workspace" not in command and "--all-targets" not in command


def test_project_policy_and_host_override_keep_distinct_owners(tmp_path, monkeypatch):
    cargo = tmp_path / "Cargo.toml"
    cargo.write_text(
        "[package.metadata.amplifier-rust-dev]\nmax_file_lines=75\n"
        "enable_structure_check=false\nenable_clippy_advisories=false\nallow_workspace_execution=true\n"
    )
    monkeypatch.delenv("AMPLIFIER_RUST_ALLOW_WORKSPACE_EXECUTION", raising=False)
    config = load_config(cargo)
    assert config.max_file_lines == 75
    assert not config.structure_enabled and not config.enable_clippy_advisories and not config.allow_workspace_execution
    monkeypatch.setenv("AMPLIFIER_RUST_ENABLE_CLIPPY_ADVISORIES", "true")
    assert load_config(cargo).enable_clippy_advisories
    assert not load_config(cargo, overrides={"enable_clippy_advisories": False}).enable_clippy_advisories
