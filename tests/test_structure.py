def source_config(**options):
    return CheckConfig(enable_cargo_fmt=False, enable_clippy=False, enable_cargo_check=False, **options)


@pytest.mark.parametrize("lines,warning", [(499, False), (500, False), (501, True)])
@pytest.mark.parametrize("ending", ["\n", "\r\n"])
def test_physical_line_threshold(tmp_path, lines, warning, ending):
    source = tmp_path / "main.rs"
    source.write_bytes((ending.join("// source" for _ in range(lines))).encode())
    result = RustChecker(source_config(), tmp_path).check_files([source])
    assert result.success and (not result.clean) is warning
    assert [issue.code for issue in result.issues] == (["FILE-LENGTH"] if warning else [])
    assert result.files_checked == 1


def test_unicode_line_separators_do_not_inflate_physical_line_count(tmp_path):
    source = tmp_path / "main.rs"
    source.write_text("// text with \u2028 and \u2029 separators\n")
    result = RustChecker(source_config(max_file_lines=1), tmp_path).check_files([source])
    assert result.clean


@pytest.mark.parametrize(
    "raw,code",
    [
        (b"todo!();\n" * 2, "FILE-LENGTH"),
        (b"todo!();\n" * 30, "STRUCTURE-SKIPPED"),
        (b"\xff", "STRUCTURE-SKIPPED"),
        ("//é\n".encode() * 5, "STRUCTURE-SKIPPED"),
    ],
)
def test_default_source_and_stub_checks_share_one_bounded_read(tmp_path, raw, code):
    source = tmp_path / "main.rs"
    source.touch()
    reads = []

    class ObservedStream(io.BytesIO):
        def read(self, size=-1):
            result = super().read(size)
            reads.append((size, len(result)))
            return result

    with patch.object(Path, "open", return_value=ObservedStream(raw)):
        result = RustChecker(source_config(max_file_lines=1, structure_max_bytes=18), tmp_path).check_files([source])
    assert reads == [(19, min(len(raw), 19))]
    assert result.issues[0].code == code
    assert result.success and not result.clean
    assert (result.files_checked == 1) == (code == "FILE-LENGTH")
    assert any(issue.code == "STUB" for issue in result.issues) == (code == "FILE-LENGTH")


def test_unreadable_source_is_skipped_not_clean(tmp_path):
    source = tmp_path / "main.rs"
    source.touch()
    with patch.object(Path, "open", side_effect=PermissionError("denied")):
        result = RustChecker(source_config(), tmp_path).check_files([source])
    assert result.issues[0].code == "STRUCTURE-SKIPPED" and not result.clean


